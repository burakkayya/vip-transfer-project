import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseColors, renderCss, renderTs } from "./sync-tokens.mjs";

const script = path.join(path.dirname(fileURLToPath(import.meta.url)), "sync-tokens.mjs");

function fixture(rootPaper, mobilePaper) {
  const dir = mkdtempSync(path.join(tmpdir(), "sync-tokens-"));
  const doc = (paper) => `---\nname: X\ncolors:\n  lacquer-black: "#0b0b0c"\n  paper: "${paper}"\ntypography:\n  body:\n    fontSize: "16px"\n---\n# Body\n`;
  writeFileSync(path.join(dir, "DESIGN.md"), doc(rootPaper));
  mkdirSync(path.join(dir, "mobile"), { recursive: true });
  writeFileSync(path.join(dir, "mobile", "DESIGN.md"), doc(mobilePaper));
  mkdirSync(path.join(dir, "web", "app"), { recursive: true });
  mkdirSync(path.join(dir, "admin", "app"), { recursive: true });
  mkdirSync(path.join(dir, "mobile", "lib"), { recursive: true });
  return dir;
}

const run = (dir, ...args) => spawnSync(process.execPath, [script, "--root", dir, ...args], { encoding: "utf8" });

test("parseColors reads the colors block only", () => {
  const md = '---\nname: X\ncolors:\n  lacquer-black: "#0B0B0C"\n  paper: "#ffffff"\ntypography:\n  body:\n    fontSize: "16px"\n---\n# Body';
  assert.deepEqual(parseColors(md), { "lacquer-black": "#0b0b0c", paper: "#ffffff" });
});

test("renderTs camelCases keys", () => {
  assert.match(renderTs({ "champagne-brass-ink": "#8a6a3c" }), /champagneBrassInk: "#8a6a3c"/);
});

test("renderCss prefixes --color-", () => {
  assert.match(renderCss({ paper: "#ffffff" }), /--color-paper: #ffffff;/);
});

test("--check fails when mobile DESIGN.md colors differ", () => {
  const dir = fixture("#ffffff", "#fefefe");
  assert.equal(run(dir).status, 1); // write also refuses to proceed on mismatch
  const res = run(dir, "--check");
  assert.equal(res.status, 1);
  assert.match(res.stdout + res.stderr, /paper/);
});

test("write then --check passes and output is byte-stable", () => {
  const dir = fixture("#ffffff", "#ffffff");
  assert.equal(run(dir).status, 0);
  const first = readFileSync(path.join(dir, "web", "app", "tokens.css"), "utf8");
  assert.match(first, /^\/\* GENERATED by scripts\/sync-tokens\.mjs — do not edit \*\/\n/);
  assert.ok(!first.includes("\r"));
  assert.equal(run(dir).status, 0);
  assert.equal(readFileSync(path.join(dir, "web", "app", "tokens.css"), "utf8"), first);
  const check = run(dir, "--check");
  assert.equal(check.status, 0);
  assert.match(check.stdout, /tokens in sync/);
  writeFileSync(path.join(dir, "admin", "app", "tokens.css"), "stale\n");
  assert.equal(run(dir, "--check").status, 1);
});
