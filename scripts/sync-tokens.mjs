#!/usr/bin/env node
// Tek renk token kaynağı: kök DESIGN.md frontmatter `colors:` bloğu.
// Üretir: web/app/tokens.css, admin/app/tokens.css, mobile/lib/tokens.ts
// Kullanım: node scripts/sync-tokens.mjs [--check] [--root <dir>]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = "GENERATED by scripts/sync-tokens.mjs — do not edit";

/** Frontmatter'daki `colors:` bloğunu okur. Anahtarlar kebab-case, değerler küçük harf hex. */
export function parseColors(markdown) {
  const lines = markdown.replace(/\r\n/g, "\n").split("\n");
  const start = lines.findIndex((l) => l.trimEnd() === "colors:");
  if (start === -1) return {};
  const colors = {};
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === "") continue;
    if (!/^\s/.test(line)) break; // ilk girintisiz satırda dur
    const m = line.match(/^ {2}([a-z0-9-]+):\s*"?(#[0-9a-fA-F]{3,8})"?\s*$/);
    if (m) colors[m[1]] = m[2].toLowerCase();
  }
  return colors;
}

const camel = (key) => key.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

export function renderCss(colors) {
  const body = Object.entries(colors).map(([k, v]) => `  --color-${k}: ${v};`).join("\n");
  return `/* ${HEADER} */\n:root {\n${body}\n}\n`;
}

export function renderTs(colors) {
  const body = Object.entries(colors).map(([k, v]) => `  ${camel(k)}: "${v}",`).join("\n");
  return `// ${HEADER}\nexport const palette = {\n${body}\n} as const;\n\nexport type PaletteKey = keyof typeof palette;\n`;
}

/** Kök ve mobil DESIGN.md renklerini karşılaştırır; fark listesini döndürür. */
export function diffColors(a, b) {
  const out = [];
  for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) {
    if (a[k] !== b[k]) out.push(`${k}: DESIGN.md=${a[k] ?? "(yok)"} mobile/DESIGN.md=${b[k] ?? "(yok)"}`);
  }
  return out;
}

function main(argv) {
  const check = argv.includes("--check");
  const ri = argv.indexOf("--root");
  const root = ri !== -1 ? path.resolve(argv[ri + 1]) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

  const colors = parseColors(readFileSync(path.join(root, "DESIGN.md"), "utf8"));
  if (Object.keys(colors).length === 0) {
    console.error("DESIGN.md: colors bloğu bulunamadı");
    return 1;
  }
  const mobileDoc = path.join(root, "mobile", "DESIGN.md");
  const problems = existsSync(mobileDoc)
    ? diffColors(colors, parseColors(readFileSync(mobileDoc, "utf8")))
    : ["mobile/DESIGN.md yok"];
  if (problems.length) {
    console.error("mobile/DESIGN.md renkleri kökten farklı:\n" + problems.map((p) => "  " + p).join("\n"));
    return 1;
  }

  const outputs = {
    "web/app/tokens.css": renderCss(colors),
    "admin/app/tokens.css": renderCss(colors),
    "mobile/lib/tokens.ts": renderTs(colors),
  };

  if (check) {
    const stale = Object.entries(outputs).filter(([rel, text]) => {
      const file = path.join(root, rel);
      return !existsSync(file) || readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== text;
    });
    if (stale.length) {
      console.error("tokens out of sync (node scripts/sync-tokens.mjs çalıştırın):\n" + stale.map(([rel]) => "  " + rel).join("\n"));
      return 1;
    }
    console.log("tokens in sync");
    return 0;
  }

  for (const [rel, text] of Object.entries(outputs)) {
    const file = path.join(root, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text, "utf8"); // LF, kararlı çıktı
    console.log("wrote " + rel);
  }
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
