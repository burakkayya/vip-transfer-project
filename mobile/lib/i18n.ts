const DICTS: Record<string, Dict> = { tr, en, de, ru };
export const LOCALE = (() => {
  if (VARIANT === "driver") return "tr";
  const code = getLocales()[0]?.languageCode ?? "en";
  return code in DICTS ? code : "en";
})();
const dict = DICTS[LOCALE];

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return dict[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function errorText(e: unknown): string {
  if (e instanceof ApiError) {
    const key = `errors.${e.code}` as Key;
    return key in dict ? dict[key] : e.code === "network" ? dict["errors.network"] : dict["errors.unknown"];
  }
  return dict["errors.unknown"];
}

/** Sürücü uygulaması için Türkçe hata metni: backend mesajı zaten Türkçedir. */
export function errorTextTr(e: unknown): string {
  if (e instanceof ApiError) return e.code === "network" ? tr["errors.network"] : e.message;
  return tr["errors.unknown"];
}

export function statusLabel(prefix: "status" | "leg", value: string): string {
  const key = `${prefix}.${value}` as Key;
  return key in dict ? dict[key] : value;
}
